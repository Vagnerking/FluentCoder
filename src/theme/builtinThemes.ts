export interface BuiltinColorTheme {
  id: string;
  label: string;
  monacoId: string;
  theme: ResolvedColorTheme;
  rules: MonacoThemeRule[];
  /** Tokens CSS a sobrescrever (vazio = os do `tokens.css`). */
  uiTokens: Record<string, string>;
  colorScheme: "dark" | "light";
  terminal: TerminalThemeColors;
}

