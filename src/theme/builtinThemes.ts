/**
 * Temas de cor EMBUTIDOS: Fluent Escuro (o padrão, `fluent-acrylic-dark` —
 * mesmas regras/cores que viviam no EditorPane), Fluent Claro e Alto Contraste.
 *
 * Cada um traz: o tema resolvido (cores do editor + `tokenColors` TextMate para
 * as gramáticas de extensões), as regras Monarch/semânticas fixas (as
 * categorias Roslyn obrigatórias de docs/context/editor.md) e os tokens da UI.
 * O Fluent Escuro NÃO sobrescreve tokens (vale o `tokens.css`).
 */
